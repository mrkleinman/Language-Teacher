#!/usr/bin/env node
// v676 (Step 0) — writes the six historical benchmark fixtures into tt.jsx (between the TT_BENCH_FIXTURES markers) so
// the in-app benchmark needs no files. Only what a run needs is embedded: id, language, track type, belt, the 30
// targets (id + new/review), the taught-word ids, the Japanese speech style, the fidelity class, and the log's sha256.
//   node benchmark/embed_fixtures.js [tt.jsx]     (idempotent; tests38 checks the embedded copy matches the files)
'use strict'
const fs = require('fs'), path = require('path')
const DIR = path.join(__dirname, 'fixtures')
const IDS = ['th-daily', 'ja-daily', 'zh-daily', 'th-listening', 'ja-listening', 'zh-listening'].map(s => s + '-2026-10-08')
function compact(fx) {
  return { id: fx.id, language: fx.language, trackType: fx.trackType, speechStyle: fx.speechStyle || null, belt: { rank: fx.belt.rank },
    targets: fx.targets.map(t => ({ id: t.id, status: t.status === 'new' ? 'new' : 'review' })), taughtIds: fx.inventory.taughtIds.slice(),
    fidelity: fx.fidelity, sourceLog: fx.historicalLog ? { file: fx.historicalLog.file, sha256: fx.historicalLog.sha256 } : null,
    historicalOutcome: fx.historicalOutcome || null,
    ...(fx.wordState ? { wordState: fx.wordState } : {}), ...(fx.clockStartMs ? { clockStartMs: fx.clockStartMs } : {}), ...(fx.capturedAt ? { capturedAt: fx.capturedAt } : {}) }
}
function embeddedBlock() {
  const list = IDS.map(id => compact(JSON.parse(fs.readFileSync(path.join(DIR, id + '.json'), 'utf8'))))
  return '// TT_BENCH_FIXTURES_BEGIN (generated by benchmark/embed_fixtures.js from benchmark/fixtures/*-2026-10-08.json — do not edit by hand)\n' +
    'const TT_BENCH_FIXTURES = ' + JSON.stringify(list) + '\n// TT_BENCH_FIXTURES_END'
}
module.exports = { embeddedBlock, compact, IDS }
if (require.main === module) {
  const file = process.argv[2] || path.join(__dirname, '..', 'tt.jsx')
  let src = fs.readFileSync(file, 'utf8')
  const re = /\/\/ TT_BENCH_FIXTURES_BEGIN[\s\S]*?\/\/ TT_BENCH_FIXTURES_END/
  const block = embeddedBlock()
  if (re.test(src)) src = src.replace(re, () => block)
  else src = src.replace('// TT_BENCH_UI_PATHS_BEGIN', () => block + '\n\n// TT_BENCH_UI_PATHS_BEGIN')
  fs.writeFileSync(file, src)
  console.log('embedded ' + IDS.length + ' fixtures (' + block.length + ' bytes) into ' + path.relative(process.cwd(), file))
}
