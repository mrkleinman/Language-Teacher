#!/usr/bin/env python3
"""Embeds thai-modules/thai-phrase-word-split.csv into tt.jsx (between the PHRASE_SPLIT_DATA markers).
Run from dev/:  python3 tools/build_phrase_split.py        (idempotent)"""
import csv, json, re, sys
HERE = __file__.rsplit('/tools/', 1)[0]
rows = list(csv.DictReader(open(HERE + '/thai-modules/thai-phrase-word-split.csv', encoding='utf-8-sig', newline='')))
phrases = [int(r['id']) for r in rows if r['entry_type'] == 'phrase']
promoted = [[int(r['id']), r['belt_proposed'], int(r['tier_proposed'].replace('T', ''))] for r in rows if r['entry_type'] == 'word']
templates = [int(r['id']) for r in rows if r['entry_type'] == 'phrase' and '...' in r['thai']]
block = ('// ══ PHRASE_SPLIT_DATA begin (generated by tools/build_phrase_split.py from thai-modules/thai-phrase-word-split.csv — do not edit by hand)\n'
        'const THAI_PHRASE_SPLIT_DATA = Object.freeze({ phrases: %s,\n  promoted: %s,\n  templates: %s })\n'
        '// ══ PHRASE_SPLIT_DATA end\n') % (json.dumps(phrases), json.dumps(promoted, ensure_ascii=False), json.dumps(templates))
p = HERE + '/tt.jsx'; s = open(p, encoding='utf-8').read()
rx = re.compile(r'// ══ PHRASE_SPLIT_DATA begin.*?// ══ PHRASE_SPLIT_DATA end\n', re.S)
if rx.search(s): s = rx.sub(lambda m: block, s)
else:
    a = 'function isCurriculumWord(w) {'
    i = s.index(a); j = s.index('\n}\n', i) + 3
    s = s[:j] + block + s[j:]
open(p, 'w', encoding='utf-8').write(s)
print('phrases', len(phrases), 'promoted', len(promoted), 'templates', templates)
