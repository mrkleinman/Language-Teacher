#!/usr/bin/env python3
"""Embeds the Cantonese word list into tt.jsx (between the YUE_BANK markers).

Single source (nothing is typed into tt.jsx by hand):
  cantonese-modules/cantonese-word-tags.csv   the word list: locked id, curriculum rank, written form (traditional, Hong Kong usage), Jyutping, Yale,
                                              meaning, belt, tier, part of speech, `skip` (a non-empty `skip` = not a word of the curriculum)
  cantonese-modules/cantonese-word-base.csv   the same rows without tags (read to prove the two files agree)

A bank row (the Mandarin field names are reused so the ~230 readers of `pinyin` keep working):
  id            the locked id of the word list (permanent: saved progress is keyed by it)
  unlockOrder   the curriculum POSITION = the list's `rank` (1 ... 2500). Since the 2026-11 gap fix the rank has NO gap (the word dropped as a Mandarin form is skipped before
                the ranking), so a belt can always be completed. If a gap ever comes back the build stops here (a belt with a gap could never be finished: rankTestStatus
                missingPositions). Ids are NOT positions, as in the Japanese bank.
  chinese       the written form, traditional characters
  pinyin        the YALE romanisation (this field name is kept for every reader; Yale for yue, never Jyutping, no tone numbers)
  jyutping      kept for the voice and for debugging; never shown
  english, partOfSpeech, tier, entryType ('word'), curriculumIndex (= unlockOrder)
Only live rows (`skip` empty) are embedded: 2,500 words (the full curriculum). There is no phrase data for Cantonese.

Run from dev/:  python3 tools/build_yue_bank.py          (idempotent)
                python3 tools/build_yue_bank.py --check  (only report; nothing is written)
"""
import csv, json, os, re, sys
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, HERE + '/tools')
import build_ja_zh_banks as B

SRC = HERE + '/cantonese-modules'
BEGIN, END = '// ══ YUE_BANK begin', '// ══ YUE_BANK end\n'
# the app's part-of-speech names (the Mandarin set: the shared code looks for 'measure word', 'proper noun', 'expression' ...)
YUE_POS = {'noun': 'noun', 'verb': 'verb', 'adj': 'adjective', 'adverb': 'adverb', 'conjunction': 'conjunction', 'proper': 'proper noun',
           'classifier': 'measure word', 'phrase': 'expression', 'pronoun': 'pronoun', 'preposition': 'preposition', 'number': 'numeral',
           'particle': 'particle', 'aspect': 'particle', 'question': 'question', 'interjection': 'expression'}
JYUTPING = re.compile(r"^[a-z]+[1-6]( [a-z]+[1-6])*$")


def rd(name):
    return list(csv.DictReader(open(SRC + '/' + name, encoding='utf-8-sig', newline='')))


def build():
    base = {r['id']: r for r in rd('cantonese-word-base.csv')}
    tags = rd('cantonese-word-tags.csv')
    out, ids, ranks = [], set(), set()
    live = sorted((t for t in tags if not t['skip']), key=lambda t: int(t['rank']))
    pos_of = {t['id']: i + 1 for i, t in enumerate(live)}
    build.moved = []
    for t in live:
        b = base[t['id']]
        assert b['word'] == t['word'] and b['yale'] == t['yale'] and b['rank'] == t['rank'], ('base/tags differ', t['id'])
        cid, rank = int(t['id']), int(t['rank'])
        assert cid not in ids and rank not in ranks, ('id or rank used twice', cid, rank)
        ids.add(cid); ranks.add(rank)
        pos = pos_of[t['id']]
        assert pos == rank, ('the list must have no gap in its ranks (position != rank)', cid, rank, pos)
        assert B.belt_for(pos) == t['belt'], ('belt does not follow the rank', cid, rank, t['belt'])
        assert t['yale'] and not re.search(r'[0-9]', t['yale']), ('Yale missing or holding a tone number', cid, t['yale'])
        assert JYUTPING.match(t['jyutping'].strip()), ('Jyutping shape', cid, t['jyutping'])
        assert t['entry_type'] == 'word' and t['pos'] in YUE_POS, ('entry type / part of speech', cid, t['pos'])
        out.append({'id': cid, 'unlockOrder': pos, 'chinese': t['word'], 'pinyin': t['yale'], 'jyutping': t['jyutping'].strip(), 'english': t['meaning'],
                    'partOfSpeech': YUE_POS[t['pos']], 'tier': t['tier'], 'entryType': 'word', 'curriculumIndex': pos})
    out.sort(key=lambda e: e['unlockOrder'])
    return out


def block(rows):
    body = ',\n'.join('  ' + json.dumps(e, ensure_ascii=False, separators=(',', ':')) for e in rows)
    return (BEGIN + ' (generated by tools/build_yue_bank.py from cantonese-modules/cantonese-word-tags.csv — do not edit by hand)\n'
            'const RAW_CANTONESE_VOCAB = [\n%s\n]\n' % body + END)


def splice(s, blk):
    rx = re.compile(re.escape(BEGIN) + r'.*?' + re.escape(END), re.S)
    if rx.search(s):
        return rx.sub(lambda m: blk, s)
    anchor = '// ══ ZH_BANK end\n'
    assert anchor in s, 'anchor not found'
    return s.replace(anchor, anchor + blk, 1)


if __name__ == '__main__':
    rows = build()
    print('cantonese', len(rows), 'words · positions', rows[0]['unlockOrder'], '-', rows[-1]['unlockOrder'], '· words whose belt differs from the list (a closed gap moved them one place):', build.moved)
    if '--check' not in sys.argv:
        p = HERE + '/tt.jsx'
        s = open(p, encoding='utf-8').read()
        open(p, 'w', encoding='utf-8').write(splice(s, block(rows)))
        print('tt.jsx updated')
